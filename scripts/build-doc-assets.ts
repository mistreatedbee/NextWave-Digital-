// Embeds the document fonts and logo so that the preview and the PDF use identical files.
// Usage: npx tsx scripts/build-doc-assets.ts [path-to-logo.jpeg]
import fs from 'node:fs'

const root = new URL('../', import.meta.url)
const data = (path: string | URL, type: string) => `data:${type};base64,${fs.readFileSync(path).toString('base64')}`
const font = (family: string, weight: number, style = 'normal') => {
  const name = family.toLowerCase()
  const file = new URL(`node_modules/@fontsource/${name}/files/${name}-latin-${weight}-${style}.woff2`, root)
  return `@font-face{font-family:'NW ${family}';font-weight:${weight};font-style:${style};src:url(${data(file, 'font/woff2')}) format('woff2')}`
}
const css = [...[400, 600, 700, 800].map((w) => font('Inter', w)), ...[400, 700].flatMap((w) => [font('Lato', w), font('Lato', w, 'italic')])].join('\n')
const logo = data(process.argv[2] ?? new URL('public/logo.jpeg', root), 'image/jpeg')
fs.writeFileSync(new URL('shared/documents/assets.generated.ts', root), `// Generated by scripts/build-doc-assets.ts. Do not edit.\nexport const FONT_CSS = ${JSON.stringify(css)}\nexport const LOGO = ${JSON.stringify(logo)}\n`)
console.log('Document assets written')
